export const POKEMON_VISUAL_NAMES = Object.freeze(Object.keys(DESIGN));

export function createPokemonPlushSvg(character, mode = 'plush') {
  const design = DESIGN[character.name];
  if (!design) return null;
  if (mode === 'silhouette') return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100"><g>${design.silhouette()}</g></svg>`;
  const content = `${design.back()}${design.main()}${design.front?.() || ''}`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">
    <defs><linearGradient id="fabric" x1="0" y1="0" x2="0.8" y2="1">
      <stop offset="0" stop-color="${design.light}"/><stop offset="1" stop-color="${design.color}"/>
    </linearGradient></defs><g stroke-linecap="round" stroke-linejoin="round">${content}</g>
  </svg>`;
}

function createImages(characters, mode) {
  return new Map(characters.map((character) => {
    const svg = createPokemonPlushSvg(character, mode);
    if (!svg) return [character.name, null];
    const image = new Image();
    image.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
    return [character.name, image];
  }));
}

export function createPokemonPlushImages(characters) { return createImages(characters, 'plush'); }
export function createPokemonSilhouetteImages(characters) { return createImages(characters, 'silhouette'); }
